# core/engine/terms_signals.py
"""
Сигнали з умов мерчанта, які впливають на вибір картки, а не на ризик.

Ризикові сигнали (скам, треті особи, зовнішні месенджери) живуть у
`core/analysis/rules.py` і йдуть через risk_engine. Тут інше: як фізично
піде переказ. Це не питання довіри до мерчанта — це питання, чи виконається
маршрут за 15 хвилин таймера.

Поки що потрібен рівно один сигнал — IBAN.
"""
from __future__ import annotations

import re

# Мерчант просить переказ на рахунок (IBAN), а не з картки на картку.
#
# Це важливо через довідник: десяток банків відправляє IBAN лише в робочі
# дні. Але сам по собі прапорець `business_days_only` нічого не означає —
# картковий переказ ті самі банки проводять і в суботу. Тому вихідні
# виводять картку з гри ТІЛЬКИ тоді, коли переказ таки піде по IBAN.
_IBAN_RE = re.compile(
    r"(?:\biban\b)"
    r"|(?:\bай[- ]?бан\b)"
    r"|(?:\bua\d{2}[\s\-]?\d{4,})"          # український IBAN у тексті умов
    r"|(?:рахунок\s+(?:в|у)\s+банку)"
    r"|(?:на\s+(?:мій\s+)?рахунок\b)"
    r"|(?:переказ\s+на\s+рахунок)",
    re.IGNORECASE,
)

# Прямі заперечення: «без IBAN», «тільки на картку». Мерчант згадав слово,
# але саме щоб сказати, що IBAN не використовує.
_IBAN_NEGATION_RE = re.compile(
    r"(?:без\s+iban)"
    r"|(?:не\s+(?:приймаю|працюю|через)\s*(?:з\s*)?iban)"
    r"|(?:iban\s+не\s+(?:приймаю|потрібен|треба))"
    r"|(?:тільки\s+(?:на\s+)?карт)"
    r"|(?:лише\s+(?:на\s+)?карт)"
    r"|(?:card\s*(?:to|2)\s*card)",
    re.IGNORECASE,
)


def mentions_iban(terms: str | None) -> bool:
    """
    Чи просить мерчант переказ по IBAN.

    Порожні умови — це НЕ «так»: вимикати картки у вихідні через те, що умов
    дістати не вдалось, означало б втрачати ордери на здогадці. Невідоме
    лишаємо невідомим, як і в решті системи (див. UNKNOWN:TERMS:EMPTY).
    """
    if not terms:
        return False
    text = str(terms)
    if _IBAN_NEGATION_RE.search(text):
        return False
    return bool(_IBAN_RE.search(text))
